CREATE TABLE `inventory_adjustments` (
  `id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
  `uuid` CHAR(36) NOT NULL,
  `company_id` INTEGER UNSIGNED NOT NULL,
  `code` VARCHAR(50) NOT NULL,
  `warehouse_id` INTEGER UNSIGNED NOT NULL,
  `status` ENUM('DRAFT','APPROVED','CANCELLED') NOT NULL DEFAULT 'DRAFT',
  `reason` VARCHAR(500) NOT NULL,
  `notes` TEXT NULL,
  `created_by_user_id` INTEGER UNSIGNED NOT NULL,
  `approved_by_user_id` INTEGER UNSIGNED NULL,
  `cancelled_by_user_id` INTEGER UNSIGNED NULL,
  `approved_at` DATETIME(3) NULL,
  `cancelled_at` DATETIME(3) NULL,
  `cancellation_reason` TEXT NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `inventory_adjustments_uuid_key` (`uuid`),
  UNIQUE INDEX `inventory_adjustments_company_code_key` (`company_id`,`code`),
  UNIQUE INDEX `inventory_adjustments_id_company_key` (`id`,`company_id`),
  INDEX `inventory_adjustments_company_status_date_idx` (`company_id`,`status`,`created_at`),
  INDEX `inventory_adjustments_warehouse_idx` (`company_id`,`warehouse_id`),
  INDEX `inventory_adjustments_created_by_idx` (`created_by_user_id`),
  INDEX `inventory_adjustments_approved_by_idx` (`approved_by_user_id`),
  INDEX `inventory_adjustments_cancelled_by_idx` (`cancelled_by_user_id`),
  CONSTRAINT `inventory_adjustments_company_id_fkey` FOREIGN KEY (`company_id`) REFERENCES `companies` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `inventory_adjustments_warehouse_id_company_id_fkey` FOREIGN KEY (`warehouse_id`,`company_id`) REFERENCES `warehouses` (`id`,`company_id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `inventory_adjustments_created_by_user_id_fkey` FOREIGN KEY (`created_by_user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `inventory_adjustments_approved_by_user_id_fkey` FOREIGN KEY (`approved_by_user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `inventory_adjustments_cancelled_by_user_id_fkey` FOREIGN KEY (`cancelled_by_user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `inventory_adjustment_details` (
  `id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
  `company_id` INTEGER UNSIGNED NOT NULL,
  `inventory_adjustment_id` INTEGER UNSIGNED NOT NULL,
  `line_number` SMALLINT UNSIGNED NOT NULL,
  `inventory_lot_id` INTEGER UNSIGNED NOT NULL,
  `location_id` INTEGER UNSIGNED NOT NULL,
  `direction` ENUM('IN','OUT') NOT NULL,
  `quantity` DECIMAL(18,4) NOT NULL,
  `unit_cost` DECIMAL(18,6) NULL,
  `total_cost` DECIMAL(18,6) NULL,
  `notes` TEXT NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `inventory_adjustment_details_line_key` (`company_id`,`inventory_adjustment_id`,`line_number`),
  UNIQUE INDEX `inventory_adjustment_details_id_company_key` (`id`,`company_id`),
  INDEX `inventory_adjustment_details_stock_idx` (`company_id`,`inventory_lot_id`,`location_id`),
  CONSTRAINT `inventory_adjustment_details_company_id_fkey` FOREIGN KEY (`company_id`) REFERENCES `companies` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `inventory_adjustment_details_inventory_adjustment_id_compan_fkey` FOREIGN KEY (`inventory_adjustment_id`,`company_id`) REFERENCES `inventory_adjustments` (`id`,`company_id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `inventory_adjustment_details_inventory_lot_id_company_id_fkey` FOREIGN KEY (`inventory_lot_id`,`company_id`) REFERENCES `inventory_lots` (`id`,`company_id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `inventory_adjustment_details_location_id_company_id_fkey` FOREIGN KEY (`location_id`,`company_id`) REFERENCES `locations` (`id`,`company_id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `inventory_adjustment_details_quantity_check` CHECK (`quantity` > 0),
  CONSTRAINT `inventory_adjustment_details_cost_check` CHECK ((`unit_cost` IS NULL OR `unit_cost` >= 0) AND (`total_cost` IS NULL OR `total_cost` >= 0))
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

